using System.Globalization;
using System.IO;
using System.Text.RegularExpressions;

namespace NicoBE;

public static class AssCommentClassifier
{
    static readonly string[] BaseColors={"white","red","pink","orange","yellow","green","cyan","blue","purple","black"};
    static readonly HashSet<string> Colors=new(BaseColors.Concat(new[]{"white2","niconicowhite","red2","truered","pink2","orange2","passionorange","yellow2","madyellow","green2","elementalgreen","cyan2","blue2","marineblue","purple2","nobleviolet","black2"}),StringComparer.Ordinal);
    static readonly Regex Move=new(@"\\move\(([^)]*)\)",RegexOptions.CultureInvariant,TimeSpan.FromSeconds(1));
    static readonly Regex Pos=new(@"\\pos\(([^)]*)\)",RegexOptions.CultureInvariant,TimeSpan.FromSeconds(1));
    static readonly Regex Tags=new(@"\{([^}]*)\}",RegexOptions.CultureInvariant,TimeSpan.FromSeconds(1));
    static bool Match(string value,string pattern)=>Regex.IsMatch(value,pattern,RegexOptions.CultureInvariant,TimeSpan.FromSeconds(1));

    // Prefer one Amatsukaze variant, never merge duplicate resolution/opacity tracks.
    public static int TrackPriority(string title)=>title switch
    {
        ContainerComments.TrackTitle=>0,
        "NicoJK-1080S"=>1,"NicoJK-720S"=>2,"NicoJK-1080T"=>3,"NicoJK-720T"=>4,
        _=>5
    };

    public static bool IsComment(string document)
    {
        if(document.Length>64*1024*1024)return false;
        bool nico=Match(document,@"(?mi)^Title:\s*NicoBE Comments\s*$");
        bool danmaku=Match(document,@"(?mi)^; Script generated by NicoDanmaku2ASS\s*$")
            && document.Contains("https://github.com/fireattack/nicodanmaku2ass",StringComparison.Ordinal);
        bool conv=true,hasComment=false;double width=0,height=0;
        var styles=new HashSet<string>(StringComparer.Ordinal);
        string section="";string[] format=Array.Empty<string>();
        using var reader=new StringReader(document);
        while(reader.ReadLine() is {} raw)
        {
            string line=raw.Trim().TrimStart('\uFEFF');
            if(line.StartsWith('[')){section=line;format=Array.Empty<string>();continue;}
            int colon=line.IndexOf(':');if(colon<0)continue;
            string key=line[..colon],value=line[(colon+1)..].TrimStart();
            if(section.Equals("[Script Info]",StringComparison.OrdinalIgnoreCase))
            {
                if(key.Equals("PlayResX",StringComparison.OrdinalIgnoreCase))double.TryParse(value,NumberStyles.Float,CultureInfo.InvariantCulture,out width);
                if(key.Equals("PlayResY",StringComparison.OrdinalIgnoreCase))double.TryParse(value,NumberStyles.Float,CultureInfo.InvariantCulture,out height);
            }
            if(key.Equals("Format",StringComparison.OrdinalIgnoreCase)){format=value.Split(',').Select(s=>s.Trim()).ToArray();continue;}
            bool style=section.Equals("[V4+ Styles]",StringComparison.OrdinalIgnoreCase)&&key.Equals("Style",StringComparison.OrdinalIgnoreCase);
            bool dialogue=section.Equals("[Events]",StringComparison.OrdinalIgnoreCase)&&key.Equals("Dialogue",StringComparison.OrdinalIgnoreCase);
            if(!style&&!dialogue)continue;
            if(format.Length==0)return false;
            string[] fields=value.Split(',',format.Length);if(fields.Length!=format.Length)return false;
            string Field(string name){int i=Array.FindIndex(format,f=>f.Equals(name,StringComparison.OrdinalIgnoreCase));return i<0?"":fields[i].Trim();}
            if(style)
            {
                string name=Field("Name");
                // Both generators emit a complete base palette, matching primary/secondary
                // colors and top-left alignment. Fonts, scaling and opacity may vary.
                string primary=Field("PrimaryColour"),secondary=Field("SecondaryColour");
                conv&=Colors.Contains(name)&&styles.Add(name)&&Field("Alignment")=="7"
                    &&Match(primary,@"^&H[0-9a-fA-F]{8}&?$")&&Match(secondary,@"^&H[0-9a-fA-F]{8}&?$")
                    &&primary.TrimEnd('&')[^6..].Equals(secondary.TrimEnd('&')[^6..],StringComparison.OrdinalIgnoreCase);
                continue;
            }
            string used=Field("Style"),content=Field("Text");
            nico&=used.StartsWith("NicoBE_Em_",StringComparison.Ordinal);
            danmaku&=Match(used,@"^Danmaku2ASS_[0-9a-fA-F]{4}$")||used=="aa";
            bool footer=IsManagementEvent(content);
            conv&=styles.Contains(used)&&Colors.Contains(used)
                &&(footer||TryPlacement(content,out _,out _,out _));
            if(!footer)hasComment=true;
        }
        // A name, footer or movement command alone must never classify ordinary subtitles.
        return hasComment&&(nico||danmaku||(conv&&width is >0 and <=16384&&height is >0 and <=16384&&BaseColors.All(styles.Contains)));
    }

    public static bool IsManagementEvent(string content)=>Match(content,
        @"^\{\\move\(0,0,0,0\)\}\[NicoConvAssData:delay=-?\d+(?:\.\d+)?random1sec=[01]:\]$");

    internal static bool TryPlacement(string content,out bool moving,out double y,out bool isMove)
    {
        moving=false;y=0;isMove=false;
        string tags=string.Concat(Tags.Matches(content).Select(m=>m.Groups[1].Value));
        if(Match(tags,@"\\(?:p[1-9]|t\()"))return false;
        var move=Move.Matches(tags).LastOrDefault();
        var pos=Pos.Matches(tags).LastOrDefault();
        var match=move??pos;if(match==null)return false;
        string[] fields=match.Groups[1].Value.Split(',');
        if(move!=null?fields.Length is not (4 or 6):fields.Length!=2)return false;
        var values=new double[fields.Length];
        for(int i=0;i<fields.Length;i++)
            if(!double.TryParse(fields[i],NumberStyles.Float,CultureInfo.InvariantCulture,out values[i])||!double.IsFinite(values[i]))return false;
        y=values[1];isMove=move!=null;
        if(isMove)
        {
            if(Math.Abs(values[3]-y)>.01||values[2]>values[0])return false;
            moving=values[2]<values[0];
        }
        return true;
    }
}
